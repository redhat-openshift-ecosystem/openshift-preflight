// offlineRun indirects through a package-level var so unit tests can
// substitute a fake instead of running real tar extraction/Pyxis calls.
var offlineRun = offline.Run

// submitOfflineArtifactsCmd implements "submit-offline-artifacts". It's a
// sub-command of `check container` so it reuses checkContainerCmd's
// persistent Pyxis flags instead of declaring its own.
func submitOfflineArtifactsCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "submit-offline-artifacts <path-to-artifacts.tar>",
		Short: "Revalidate and submit results generated by a disconnected (offline) run",
		Long: `This command takes the artifacts.tar produced by "preflight check container --offline"
on a disconnected host and, once it has been copied to a host with access to Red Hat
services, finishes certification by:
  - Revalidating any checks that could not complete while offline (e.g. BasedOnUbi,
    which requires reaching Pyxis).
  - Preserving every other result that was already completed offline.
  - Submitting the finalized results to Red Hat, without requiring you to
    construct or run any Pyxis API calls by hand.`,
		Example: "  preflight check container submit-offline-artifacts ./artifacts/artifacts.tar",
		Args:    cobra.ExactArgs(1),
		// Hidden so this doesn't show up in `check container --help`'s
		// subcommand list or in generated docs while this is still a POC;
		// it remains fully usable when invoked directly by name.
		Hidden: true,
		// validateCertificationComponentID is called explicitly here (not
		// inherited via PersistentPreRunE) since it's declared as a plain
		// PreRunE on checkContainerCmd; see that file for why.
		PreRunE: func(cmd *cobra.Command, args []string) error {
			if err := validateCertificationComponentID(cmd, args); err != nil {
				return err
			}
			return validateSubmitOfflineArtifactsFlags(cmd)
		},
		RunE: submitOfflineArtifactsRunE,
	}

	return cmd
}

// validateSubmitOfflineArtifactsFlags ensures Pyxis credentials are present
// (submit-offline-artifacts always submits). A value can come from the flag
// or its PFLT_* env var, so presence is checked as Changed OR viper.IsSet.
func validateSubmitOfflineArtifactsFlags(cmd *cobra.Command) error {
	v := viper.Instance()

	// --docker-config is inherited from checkCmd, but never forwarded: this
	// command only submits already-extracted results and never pulls or
	// inspects the original image. Reject it rather than silently ignoring it.
	if v.GetString("dockerConfig") != "" {
		return fmt.Errorf("--docker-config is not supported with submit-offline-artifacts")
	}

	componentIDChanged := cmd.Flag("certification-component-id").Changed
	if !componentIDChanged && !v.IsSet("certification_component_id") {
		return fmt.Errorf("certification component ID must be specified to submit offline artifacts")
	}
	if componentIDChanged && v.GetString("certification_component_id") == "" {
		return fmt.Errorf("certification component ID cannot be empty to submit offline artifacts")
	}

	tokenChanged := cmd.Flag("pyxis-api-token").Changed
	if !tokenChanged && !v.IsSet("pyxis_api_token") {
		return fmt.Errorf("pyxis API Token must be specified to submit offline artifacts")
	}
	if tokenChanged && v.GetString("pyxis_api_token") == "" {
		return fmt.Errorf("pyxis API Token cannot be empty to submit offline artifacts")
	}

	// Guards against a missing flag value being parsed as the next flag,
	// e.g. `--pyxis-api-token --certification-component-id abc123`.
	if strings.HasPrefix(v.GetString("pyxis_api_token"), "--") || strings.HasPrefix(v.GetString("certification_component_id"), "--") {
		return fmt.Errorf("pyxis API token and certification component ID are required to submit offline artifacts")
	}

	return nil
}

func submitOfflineArtifactsRunE(cmd *cobra.Command, args []string) error {
	ctx := cmd.Context()
	logger, err := logr.FromContext(ctx)
	if err != nil {
		//coverage:ignore
		return fmt.Errorf("invalid logging configuration")
	}

	v := viper.Instance()

	cfg, err := runtime.NewConfigFrom(*v)
	if err != nil {
		//coverage:ignore
		return fmt.Errorf("invalid configuration: %w", err)
	}

	opts := offline.Options{
		ArtifactsTarPath:         args[0],
		LogFile:                  cfg.LogFile,
		PyxisHost:                cfg.PyxisHost,
		PyxisAPIToken:            cfg.PyxisAPIToken,
		CertificationComponentID: cfg.CertificationComponentID,
	}

	cmd.SilenceUsage = true

	summary, err := offlineRun(ctx, opts)
	if err != nil {
		return err
	}

	logger.Info("submit-offline-artifacts complete",
		"extractDir", summary.ExtractDir,
		"submitted", summary.Submitted,
	)

	return nil
}
